#!/usr/bin/env python3
"""Keep the documents referencing each other (docs/README.md "Cross-references").

    python3 tools/doc_backlinks.py            # rewrite the generated "Referenced by" blocks
    python3 tools/doc_backlinks.py --check    # exit 1 if any block is stale (tools/check_docs.py runs this)

RULE. If document A links document B, B must link back to A. The author of A normally cites B in prose; B's
author cannot know. So each document ends with a generated block, between the markers below, listing every
document that links it but that it does not already link in its own text. Writing the block is mechanical
and idempotent: the links inside the block are never counted when deciding what to list, so running the
tool twice changes nothing.

SCOPE. Every Markdown file under docs/ (including docs/legacy/). docs/README.md is the index: it links
everything and is linked from every control line, so it is exempt on both sides. Links outside docs/
(CLAUDE.md, source files, the repository README) are not managed.

ALSO CHECKED. A controlled document with no link to any other document is reported (an island).
Never edit a generated block by hand: change the citing document instead.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path
from urllib.parse import unquote, urlsplit
import os

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
START = "<!-- backlinks:start (generated by tools/doc_backlinks.py; do not edit) -->"
END = "<!-- backlinks:end -->"
LINK = re.compile(r"!??\[[^\]]*\]\((?:<([^>]+)>|([^\s)]+))(?:\s+[^)]*)?\)")
CONTROL = re.compile(r"^> \*\*Document control:\*\* (?:\[(?P<a>[A-Z]{3}-\d{3})\]\([^)]*\)|(?P<b>[A-Z]{3}-\d{3}))", re.M)
BLOCK = re.compile(re.escape(START) + r".*?" + re.escape(END) + r"\n?", re.S)


def docs() -> list[Path]:
    return sorted(p for p in DOCS.rglob("*.md") if p != DOCS / "README.md")


def strip_block(text: str) -> str:
    return BLOCK.sub("", text)


def doc_id(text: str, path: Path) -> str:
    m = CONTROL.search(text)
    return (m.group("a") or m.group("b")) if m else path.stem.upper()


def title(text: str) -> str:
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return ""


def outgoing(path: Path, text: str, known: set[Path]) -> set[Path]:
    out: set[Path] = set()
    for m in LINK.finditer(strip_block(text)):
        raw = m.group(1) or m.group(2) or ""
        p = urlsplit(raw)
        if p.scheme or p.netloc or not p.path:
            continue
        tgt = (path.parent / unquote(p.path)).resolve()
        if tgt in known and tgt != path.resolve():
            out.add(tgt)
    return out


def compute() -> tuple[dict[Path, str], list[str]]:
    """({path: new full text}, [island paths])."""
    files = docs()
    known = {p.resolve() for p in files}
    texts = {p.resolve(): p.read_text(encoding="utf-8") for p in files}
    out = {p: outgoing(p, t, known) for p, t in texts.items()}
    incoming: dict[Path, set[Path]] = {p: set() for p in known}
    for a, targets in out.items():
        for b in targets:
            incoming[b].add(a)
    new: dict[Path, str] = {}
    islands: list[str] = []
    for p, text in texts.items():
        base = strip_block(text).rstrip("\n")
        need = sorted(a for a in incoming[p] if a not in out[p])
        if not out[p] and not incoming[p]:
            islands.append(str(p.relative_to(ROOT)))
        if need:
            lines = [START, "## Referenced by", ""]
            for a in need:
                rel = os.path.relpath(a, p.parent)
                lines.append(f"- [{doc_id(texts[a], a)}]({rel}): {title(texts[a])}")
            lines.append(END)
            new[p] = base + "\n\n" + "\n".join(lines) + "\n"
        else:
            new[p] = base + "\n"
    return new, islands


def main(argv: list[str]) -> int:
    check = "--check" in argv
    new, islands = compute()
    stale = [p for p, t in new.items() if p.read_text(encoding="utf-8") != t]
    if check:
        for p in stale:
            print(f"- {p.relative_to(ROOT)}: generated 'Referenced by' block is stale "
                  "(run python3 tools/doc_backlinks.py)", file=sys.stderr)
        for i in islands:
            print(f"- {i}: links to no other document and no document links it", file=sys.stderr)
        return 1 if stale or islands else 0
    for p in stale:
        p.write_text(new[p], encoding="utf-8")
    print(f"updated {len(stale)} of {len(new)} documents; islands: {islands or 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
